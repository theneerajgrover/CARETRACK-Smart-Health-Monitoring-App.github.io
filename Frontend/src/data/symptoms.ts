export function getAllSymptoms(): { key: string; label: string; category: string; categoryLabel: string }[] {
  return SYMPTOM_CATEGORIES.flatMap((cat) =>
    cat.symptoms.map((s) => ({
      key: s.key,
      label: s.label,
      category: cat.id,
      categoryLabel: cat.label,
    }))
  )
}

export function formatSymptomKey(key: string): string {
  return key
    .split('_')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ')
}
